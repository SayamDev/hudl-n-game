import type { ComponentType } from "react";
export type GameId = "imposter" | "mafia" | "spy" | "charades" | "party";
export type Player = {
  id: string;
  name: string;
  avatar: string;
  color: string;
  score: number;
};
export type Pack = {
  id: string;
  name: string;
  words: string[];
  adult?: boolean;
};
export type Preferences = {
  deckStyle?: boolean;
  design: "club" | "club-original" | "classic";
  dark: boolean;
  family: boolean;
  adult: boolean;
  sound: boolean;
  countdown?: boolean;
  volume: number;
  haptics: boolean;
  narrator: boolean;
  voice: string;
  rate: number;
  largeText: boolean;
  contrast: boolean;
};
export type GameOptions = {
  imposters: number;
  randomImposters: boolean;
  hint: boolean;
  hintStyle?: "word" | "category";
  voteFlowVersion?: number;
  charadesMode?: "heads-up" | "classic";
  chaos: boolean;
  seconds: number;
  packIds: string[];
  voteMode: "secret" | "point";
  points: number;
  doctor: boolean;
  detective: boolean;
  jester: boolean;
  bodyguard: boolean;
  vigilante: boolean;
  showRoles: boolean;
  manual: boolean;
  tilt: boolean;
  intensity: "Family" | "Friends" | "Spicy";
  partyMode: "likely" | "takes";
};
export type Session = {
  id: string;
  game: GameId;
  phase: string;
  options: GameOptions;
  roles: Record<string, string>;
  secret: string;
  category: string;
  decoy: string;
  actorIndex?: number;
  peekIndex: number;
  alive: string[];
  votes: Record<string, string>;
  voterIndex: number;
  accused: string | null;
  round: number;
  night: Record<string, string>;
  history: string[];
  result: string;
  winners: string[];
  awarded: boolean;
  deck: string[];
  cardIndex: number;
  correct: number;
  skipped: number;
  teamScores: [number, number];
  team: number;
  timerRemaining: number;
  timerRunning: boolean;
  paused: boolean;
  startingPlayer: string;
  direction: string;
  guessOptions: string[];
  partyVotes: Record<string, number>;
  promptIndex: number;
  promptDeck?: string[];
};
export type GameProps = { session: Session };
export type SettingsProps = {
  game: GameId;
  onStart: () => void;
  onPlayers?: () => void;
};
export type ResultsProps = {
  session: Session;
  onHome: () => void;
  onPlayers: () => void;
};
export type GameDefinition = {
  id: GameId;
  name: string;
  subtitle: string;
  color: string;
  emoji: string;
  min: number;
  duration: string;
  rules: string[];
  load: () => Promise<{ default: ComponentType<GameProps> }>;
  settings: () => Promise<{ default: ComponentType<SettingsProps> }>;
  results: () => Promise<{ default: ComponentType<ResultsProps> }>;
};
